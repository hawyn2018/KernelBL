"""Build a standalone PIC binary/manifest; Kotlin export is explicitly opt-in."""
from pathlib import Path
import subprocess, hashlib, base64, json, os, shutil
from elftools.elf.elffile import ELFFile
HERE=Path(__file__).resolve().parent
ROOT=HERE.parents[1]
OUT=ROOT/'build'/'kbl-parent'

def tool(name, llvm_bin=None):
 configured=llvm_bin or os.environ.get('LLVM_BIN')
 names=(name+'.exe',name) if os.name=='nt' else (name,name+'.exe')
 if configured:
  directory=Path(configured).expanduser().resolve()
  for candidate in names:
   path=directory/candidate
   if path.is_file():return path
  raise FileNotFoundError(f'{name} not found in LLVM directory: {directory}')
 for candidate in names:
  found=shutil.which(candidate)
  # Keep ld.lld's entry name: Unix installations often symlink it to lld,
  # whose multi-call driver chooses its flavor from argv[0].
  if found:return Path(found).absolute()
 raise FileNotFoundError(f'{name} not found; pass --llvm-bin, set LLVM_BIN, or add LLVM tools to PATH')
def run(args):
 p=subprocess.run([str(x) for x in args],capture_output=True,text=True)
 if p.returncode: raise RuntimeError(p.stdout+p.stderr)
 return p.stdout
def main(output=None,llvm_bin=None,kotlin_output=None):
 global OUT
 if output is not None:OUT=Path(output).resolve()
 OUT.mkdir(parents=True,exist_ok=True)
 clang,lld=tool('clang',llvm_bin),tool('ld.lld',llvm_bin)
 obj=OUT/'parent.o'; elf=OUT/'parent.elf'; blob=OUT/'parent.bin'
 run([clang,'--target=aarch64-none-elf','-O2','-std=c11','-Wall','-Wextra','-Werror',
 '-ffreestanding','-fno-builtin','-fno-stack-protector','-fPIC','-fvisibility=hidden','-ffixed-x18',
 '-mgeneral-regs-only','-fno-jump-tables','-fno-unwind-tables','-fno-asynchronous-unwind-tables',
 '-c',HERE/'kbl_parent_shim.c','-o',obj])
 run([lld,'-T',HERE/'kbl_parent_shim.ld','--no-undefined','--fatal-warnings',obj,'-o',elf])
 with elf.open('rb') as f:
  e=ELFFile(f); sym=e.get_section_by_name('.symtab')
  assert not [s.name for s in sym.iter_symbols() if s.name and s['st_shndx']=='SHN_UNDEF']
  assert not [s.name for s in e.iter_sections() if s['sh_type'] in ('SHT_REL','SHT_RELA','SHT_DYNAMIC')]
  assert e['e_entry']==0
  assert not any(s['sh_size'] for s in e.iter_sections() if s.name in ('.bss','.data','.got','.got.plt'))
  data=e.get_section_by_name('.module').data()
  lazy_entry=next(s['st_value'] for s in sym.iter_symbols() if s.name=='kbl_parent_lazy_start')
 blob.write_bytes(data)
 sha=hashlib.sha256(data).hexdigest()
 b64=base64.b64encode(data).decode()
 kotlin=('package net.hawyn.ablefisp.patch\n\n// Generated by runtime/uefi/build_parent_shim.py; PIC, no relocation/import.\ninternal object KblParentModule {\n    const val SHA256 = "'+sha+'"\n    const val LAZY_START_OFFSET = '+str(lazy_entry)+'L\n    val bytes: ByteArray get() = java.util.Base64.getDecoder().decode(\n'+
 '\n'.join('        "'+b64[i:i+120]+'"'+(' +' if i+120<len(b64) else '') for i in range(0,len(b64),120))+'\n    )\n}\n')
 if kotlin_output is not None:
  destination=Path(kotlin_output).expanduser().resolve()
  destination.parent.mkdir(parents=True,exist_ok=True)
  destination.write_text(kotlin,encoding='utf-8')
 report={'bytes':len(data),'sha256':sha,'entry':0,'lazy_start_offset':lazy_entry,'undefined':0,'dynamic_relocations':0,'mutable_sections':0,
 'sources_sha256':{str(p.relative_to(ROOT)):hashlib.sha256(p.read_bytes()).hexdigest() for p in
 [HERE/'kbl_parent_shim.c',HERE/'kbl_parent_shim.h',HERE/'kbl_parent_shim.ld',HERE/'kbl_service.h']},
 'deviceOperations':False,'binary':str(blob),'kotlinOutput':str(destination) if kotlin_output is not None else None,
 'tools':{name:{'path':str(path),'sha256':hashlib.sha256(path.read_bytes()).hexdigest()} for name,path in [('clang',clang),('ld.lld',lld)]}}
 (OUT/'manifest.json').write_text(json.dumps(report,indent=2)+'\n',encoding='utf-8')
 print(json.dumps(report))
 return report
if __name__=='__main__':
 import argparse
 parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--output',type=Path,default=OUT)
 parser.add_argument('--llvm-bin',type=Path,help='LLVM directory; otherwise LLVM_BIN then PATH')
 parser.add_argument('--kotlin-output',type=Path,help='Explicit optional .kt destination; omitted by default')
 args=parser.parse_args();main(args.output,args.llvm_bin,args.kotlin_output)
